//! Rendering to Xen's `xl` domain configuration format, plus the Xen
//! command line that shapes dom0.
//!
//! This is the bootstrap backend: it lets a rustBOX topology run on a stock
//! Xen toolstack today. The native backend (direct hypercalls from the Rust
//! dom0) will consume the same [`ValidSystem`].
//!
//! Strings are interpolated without escaping. That is sound because
//! [`ValidSystem`] guarantees names, paths and command lines are drawn from
//! alphabets that cannot terminate a quoted string or a disk-spec field.

use std::fmt::Write;

use crate::policy::ValidSystem;
use crate::spec::{Role, Virt};

/// Xen's OUI; the low three bytes are derived per qube.
const XEN_OUI: [u8; 3] = [0x00, 0x16, 0x3e];

/// Renders the `xl` configuration of one qube. Returns `None` for dom0
/// (which Xen itself builds, see [`xen_cmdline`]) and for unknown names.
pub fn render(system: &ValidSystem, name: &str) -> Option<String> {
    let spec = system.spec();
    let q = spec.qube(name).filter(|q| q.role != Role::Dom0)?;
    let virt = q.effective_virt();
    let mut out = String::new();
    let o = &mut out;

    // `writeln!` to a String cannot fail.
    let _ = writeln!(
        o,
        "# rustBOX qube `{}` (role {}) of system `{}`.",
        q.name,
        q.role.as_str(),
        spec.system.name
    );
    let _ = writeln!(
        o,
        "# Generated by rbx; edit the system description instead."
    );
    let _ = writeln!(o, "name = \"{}\"", q.name);
    let _ = writeln!(o, "type = \"{}\"", virt.as_str());
    let _ = writeln!(o, "vcpus = {}", q.vcpus);
    // Fixed allocation: passthrough domains cannot balloon, and a fixed
    // footprint keeps one qube from starving another.
    let _ = writeln!(o, "memory = {}", q.memory_mb);
    let _ = writeln!(o, "maxmem = {}", q.memory_mb);
    for event in ["on_poweroff", "on_reboot", "on_crash"] {
        let _ = writeln!(o, "{event} = \"destroy\"");
    }

    if virt == Virt::Hvm {
        // Run the device model in its own stub domain so a QEMU compromise
        // lands in a deprivileged domain instead of dom0.
        let _ = writeln!(o, "device_model_version = \"qemu-xen\"");
        let _ = writeln!(o, "device_model_stubdomain_override = 1");
        if q.iso.is_some() {
            let _ = writeln!(o, "boot = \"dc\"");
        }
    }
    if q.role.provides_network() {
        let _ = writeln!(o, "driver_domain = 1");
    }

    if let Some(kernel) = &q.kernel {
        let _ = writeln!(o, "kernel = \"{kernel}\"");
        if let Some(ramdisk) = &q.ramdisk {
            let _ = writeln!(o, "ramdisk = \"{ramdisk}\"");
        }
        if let Some(cmdline) = &q.cmdline {
            let _ = writeln!(o, "cmdline = \"{cmdline}\"");
        }
    }

    let mut disks = Vec::new();
    for (i, disk) in q.disks.iter().enumerate() {
        let format = if disk.path.ends_with(".qcow2") {
            "qcow2"
        } else {
            "raw"
        };
        let access = if disk.readonly { "ro" } else { "rw" };
        disks.push(format!(
            "format={format},vdev={},access={access},target={}",
            disk_name(i),
            disk.path
        ));
    }
    if let Some(iso) = &q.iso {
        disks.push(format!(
            "format=raw,vdev=hdc,access=ro,devtype=cdrom,target={iso}"
        ));
    }
    write_list(o, "disk", &disks);

    let pci: Vec<String> = q
        .pci
        .iter()
        .map(|p| {
            if p.permissive {
                format!("{},permissive=1", p.bdf)
            } else {
                p.bdf.to_string()
            }
        })
        .collect();
    write_list(o, "pci", &pci);

    if let Some(netvm) = &q.netvm {
        let vif = format!(
            "mac={},backend={netvm}",
            mac_address(&spec.system.name, &q.name)
        );
        write_list(o, "vif", &[vif]);
    }
    Some(out)
}

/// The Xen hypervisor command line for this system: a PVH dom0 with the
/// declared size, a mandatory IOMMU (no passthrough without DMA
/// protection) and SMT off.
pub fn xen_cmdline(system: &ValidSystem) -> String {
    let dom0 = system.dom0();
    format!(
        "dom0=pvh dom0_mem={mem}M,max:{mem}M dom0_max_vcpus={vcpus} iommu=required smt=off ucode=scan",
        mem = dom0.memory_mb,
        vcpus = dom0.vcpus
    )
}

/// A stable, locally administered-looking MAC under Xen's OUI. Stable so a
/// qube keeps its address (and DHCP lease, firewall rules) across restarts.
pub fn mac_address(system: &str, qube: &str) -> String {
    // FNV-1a over "system/qube".
    let mut hash: u32 = 0x811c_9dc5;
    for b in system
        .bytes()
        .chain(std::iter::once(b'/'))
        .chain(qube.bytes())
    {
        hash ^= b as u32;
        hash = hash.wrapping_mul(0x0100_0193);
    }
    let [_, a, b, c] = hash.to_be_bytes();
    let [x, y, z] = XEN_OUI;
    format!("{x:02x}:{y:02x}:{z:02x}:{a:02x}:{b:02x}:{c:02x}")
}

/// xvda, xvdb, ... xvdz, xvdaa, ...
fn disk_name(index: usize) -> String {
    let mut suffix = Vec::new();
    let mut n = index;
    loop {
        suffix.push(b'a' + (n % 26) as u8);
        if n < 26 {
            break;
        }
        n = n / 26 - 1;
    }
    suffix.reverse();
    format!("xvd{}", String::from_utf8(suffix).expect("ascii"))
}

fn write_list(o: &mut String, key: &str, items: &[String]) {
    if items.is_empty() {
        return;
    }
    let _ = writeln!(o, "{key} = [");
    for item in items {
        let _ = writeln!(o, "    \"{item}\",");
    }
    let _ = writeln!(o, "]");
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::spec::SystemSpec;

    const SYSTEM: &str = r#"
        [system]
        name = "t"
        guivm = "sys-gui"

        [[qube]]
        name = "dom0"
        role = "dom0"
        memory_mb = 1024
        vcpus = 2

        [[qube]]
        name = "sys-net"
        role = "net"
        memory_mb = 512
        pci = [
            { bdf = "02:00.0", class = "nic" },
            { bdf = "03:00.0", class = "nic", permissive = true },
        ]
        disks = [{ path = "/var/lib/rbx/sys-net.qcow2" }]

        [[qube]]
        name = "sys-gui"
        role = "gui"
        memory_mb = 2048
        pci = [{ bdf = "00:02.0", class = "gpu" }]
        disks = [{ path = "/var/lib/rbx/sys-gui.img" }]

        [[qube]]
        name = "work"
        role = "app"
        label = "blue"
        memory_mb = 1024
        vcpus = 2
        netvm = "sys-net"
        kernel = "/boot/rbx/vmlinuz"
        ramdisk = "/boot/rbx/initrd"
        cmdline = "root=/dev/xvda ro quiet"
        disks = [{ path = "/var/lib/rbx/work-root.img", readonly = true }, { path = "/var/lib/rbx/work-home.img" }]

        [[qube]]
        name = "win"
        role = "standalone"
        label = "orange"
        memory_mb = 8192
        vcpus = 4
        iso = "/var/lib/rbx/iso/install.iso"
        disks = [{ path = "/var/lib/rbx/win.img" }]
        pci = [{ bdf = "01:00.0", class = "gpu" }, { bdf = "01:00.1", class = "audio" }]
    "#;

    fn with_system<T>(f: impl FnOnce(&ValidSystem) -> T) -> T {
        let spec = SystemSpec::parse(SYSTEM).unwrap();
        let (system, warnings) = ValidSystem::new(&spec).unwrap();
        assert_eq!(warnings.issues, vec![]);
        f(&system)
    }

    #[test]
    fn pvh_app_qube() {
        let cfg = with_system(|s| render(s, "work").unwrap());
        let mac = mac_address("t", "work");
        assert_eq!(
            cfg,
            format!(
                r#"# rustBOX qube `work` (role app) of system `t`.
# Generated by rbx; edit the system description instead.
name = "work"
type = "pvh"
vcpus = 2
memory = 1024
maxmem = 1024
on_poweroff = "destroy"
on_reboot = "destroy"
on_crash = "destroy"
kernel = "/boot/rbx/vmlinuz"
ramdisk = "/boot/rbx/initrd"
cmdline = "root=/dev/xvda ro quiet"
disk = [
    "format=raw,vdev=xvda,access=ro,target=/var/lib/rbx/work-root.img",
    "format=raw,vdev=xvdb,access=rw,target=/var/lib/rbx/work-home.img",
]
vif = [
    "mac={mac},backend=sys-net",
]
"#
            )
        );
    }

    #[test]
    fn net_qube_is_an_hvm_driver_domain_with_its_nics() {
        let cfg = with_system(|s| render(s, "sys-net").unwrap());
        assert!(cfg.contains("type = \"hvm\"\n"));
        assert!(cfg.contains("driver_domain = 1\n"));
        assert!(cfg.contains("device_model_stubdomain_override = 1\n"));
        assert!(
            cfg.contains("pci = [\n    \"0000:02:00.0\",\n    \"0000:03:00.0,permissive=1\",\n]\n")
        );
        assert!(
            cfg.contains("\"format=qcow2,vdev=xvda,access=rw,target=/var/lib/rbx/sys-net.qcow2\"")
        );
        assert!(
            !cfg.contains("vif"),
            "the uplink qube has no virtual NIC of its own"
        );
        assert!(!cfg.contains("\nboot ="), "nothing asks for a boot order");
    }

    #[test]
    fn byo_iso_hvm_boots_the_cdrom_first_and_gets_its_gpu() {
        let cfg = with_system(|s| render(s, "win").unwrap());
        assert!(cfg.contains("type = \"hvm\"\n"));
        assert!(cfg.contains("boot = \"dc\"\n"));
        assert!(cfg.contains(
            "\"format=raw,vdev=hdc,access=ro,devtype=cdrom,target=/var/lib/rbx/iso/install.iso\""
        ));
        assert!(cfg.contains("pci = [\n    \"0000:01:00.0\",\n    \"0000:01:00.1\",\n]\n"));
        assert!(!cfg.contains("vif"), "no netvm was requested");
        assert!(!cfg.contains("driver_domain"));
    }

    #[test]
    fn dom0_and_unknown_names_have_no_domain_config() {
        with_system(|s| {
            assert_eq!(render(s, "dom0"), None);
            assert_eq!(render(s, "nope"), None);
        });
    }

    #[test]
    fn xen_cmdline_pins_dom0_down() {
        let cmdline = with_system(xen_cmdline);
        assert_eq!(
            cmdline,
            "dom0=pvh dom0_mem=1024M,max:1024M dom0_max_vcpus=2 iommu=required smt=off ucode=scan"
        );
    }

    #[test]
    fn mac_addresses_are_stable_distinct_and_under_the_xen_oui() {
        let a = mac_address("t", "work");
        assert_eq!(a, mac_address("t", "work"));
        assert!(a.starts_with("00:16:3e:"));
        assert_eq!(a.len(), 17);
        assert_ne!(a, mac_address("t", "vault"));
        assert_ne!(a, mac_address("u", "work"));
        // The separator keeps ("ab", "c") and ("a", "bc") apart.
        assert_ne!(mac_address("ab", "c"), mac_address("a", "bc"));
    }

    #[test]
    fn disk_names_continue_past_z() {
        assert_eq!(disk_name(0), "xvda");
        assert_eq!(disk_name(25), "xvdz");
        assert_eq!(disk_name(26), "xvdaa");
        assert_eq!(disk_name(27), "xvdab");
        assert_eq!(disk_name(26 + 26 * 26 - 1), "xvdzz");
        assert_eq!(disk_name(26 + 26 * 26), "xvdaaa");
    }
}
